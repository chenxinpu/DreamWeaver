/** 将 path 描述中 "x y" 数字对按 mirror=300-x 翻转（保留 M/L/C/Z 等指令字） */
export function mirrorD(d: string): string {
  return d.replace(/(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)/g, (_m, x: string, y: string) => {
    return `${(300 - parseFloat(x)).toFixed(2)} ${y}`;
  });
}

